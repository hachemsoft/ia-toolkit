"""sync and rollback of the Core source (V2 slice 2, docs/v2/git-sync.md), and the locked content every other command uses.

activation() is wrapped around the existing apply(): it takes the engine lock, resumes an interrupted activation, chooses
the content (the locked Core, a newly fetched tag, or the previous configuration) and gives apply() the new lock.toml to
write in the same transaction. Without a Core source configured and locked, the content stays the package's (V1)."""
import contextlib

from .commit import resume_pending
from .config import AIKIT_FILE, check_source, load_aikit, load_managed
from .core import ROOT, KitError, content_from
from .sources import (EngineLock, SourceError, authorize, cache_dir, canonical_url, check_seen, choose_tag, extract, fetch, new_temp,
                      prune_cache, remote_tags, remove_temp, revoked)
from .toml_files import dump_toml, read_toml

LOCK_FILE = 'lock.toml'
LOCK_HEADER = '# Generated by ai-kit. Do not edit: ai-kit sync and ai-kit rollback write it.\n'


def engine_version():
    return (ROOT/'VERSION').read_text(encoding='utf-8').strip()


def read_lock(kit):
    return read_toml(kit/LOCK_FILE, {})


def lock_bytes(current, previous):
    data = {'engine': engine_version(), **current}
    if previous:
        data['previous'] = previous
    return (LOCK_HEADER + dump_toml(data)).encode('utf-8')


def git_settings(home, managed):
    """Effective git.* keys: managed.toml wins key by key; the person may only allow prereleases when IT does not decide."""
    mine = {}
    if (home/'.ai-kit'/AIKIT_FILE).exists():
        mine = load_aikit(home/'.ai-kit'/AIKIT_FILE)[0]
    settings = {'allowed_hosts': [], 'allowed_groups': [], 'allowed_schemes': ['https', 'ssh'], 'allow_prerelease': False, 'revoked': []}
    if 'allow_prerelease' in mine.get('git', {}):
        settings['allow_prerelease'] = mine['git']['allow_prerelease']
    settings.update((managed or {}).get('git', {}))
    core = (managed or {}).get('enterprise', {}).get('core') or mine.get('core', {}).get('repo')
    return settings, core, bool((managed or {}).get('enterprise', {}).get('core'))


def check_origin(url, settings):
    canonical = canonical_url(url, tuple(settings['allowed_schemes']))
    authorize(canonical, settings)
    return canonical


def materialize(kit, entry, settings):
    """The tree of a lock entry extracted into a new temporary folder, its digest checked against the lock."""
    if revoked(entry['commit'], settings):
        raise SourceError('revoked', 'The commit '+entry['commit']+' ('+entry['tag']+') is revoked by IT (managed.toml git.revoked): run ai-kit sync.')
    cache = cache_dir(kit, entry['url'])
    if not (cache/'HEAD').exists():
        raise SourceError('not-found', 'The Core '+entry['tag']+' is not in the local cache: run ai-kit sync (network needed).')
    folder = new_temp()
    try:
        got = extract(kit, cache, entry['commit'], folder)
        if got != entry['tree_digest']:
            raise SourceError('invalid', 'The cached Core '+entry['tag']+' does not match lock.toml (tree digest): run ai-kit sync.')
        manifest = check_source(folder, engine_version())
        if manifest is None:
            raise SourceError('invalid', 'The Core '+entry['tag']+' has no aikit.toml manifest at its root.')
        return folder
    except BaseException:
        remove_temp(folder)
        raise


@contextlib.contextmanager
def activation(home, action, dry_run=False, confirm=None, managed_file=None, guardrail_names=()):
    """Yields the extra writes for apply() (lock.toml for sync and rollback), with the content root set to the active Core."""
    kit = home/'.ai-kit'
    managed = load_managed(managed_file, guardrail_names)
    settings, core_url, anchored = git_settings(home, managed)
    lock = read_lock(kit)
    locker = contextlib.nullcontext() if dry_run else EngineLock(kit)
    with locker:
        if not dry_run:
            restored = resume_pending(home, kit)
            if restored:
                print('[Info] An activation was interrupted: the files of '+restored.name+' were put back before continuing.')
                lock = read_lock(kit)
        current = lock.get('sources', {}).get('core')
        folder, extra, summary = None, {}, None
        try:
            if action == 'sync':
                if not core_url:
                    raise KitError('No Core source: set [core] repo = "<URL>" in ~/.ai-kit/aikit.toml, or IT sets enterprise.core in managed.toml.')
                url = check_origin(core_url, settings)
                tags = remote_tags(url, kit, tuple(settings['allowed_schemes']))
                check_seen(kit, url, tags)
                same_origin = current and current.get('url') == url
                tag = choose_tag(tags, current['tag'] if same_origin else None, settings['allow_prerelease'])
                announced = tags[tag]
                if revoked(announced['commit'], settings):
                    raise SourceError('revoked', 'The Core '+tag+' is revoked by IT (managed.toml git.revoked); nothing was changed.')
                if not same_origin and not anchored:
                    # First use of an origin outside managed mode: the person confirms what will be trusted (ADR 0016).
                    question = ('First use of this Core: '+url+' at '+tag+' (commit '+announced['commit'][:12]+'). Trust it?')
                    if confirm is None or not confirm(question):
                        raise KitError('First use of '+url+' needs your confirmation in a terminal: run ai-kit sync there.')
                cache = fetch(kit, url, tag, announced['commit'], tuple(settings['allowed_schemes']))
                folder = new_temp()
                digest = extract(kit, cache, announced['commit'], folder)
                if check_source(folder, engine_version()) is None:
                    raise SourceError('invalid', 'The Core '+tag+' has no aikit.toml manifest at its root; nothing was changed.')
                entry = {'url': url, 'tag': tag, 'tag_object': announced['tag_object'], 'commit': announced['commit'], 'tree_digest': digest}
                unchanged = current == entry
                previous = lock.get('previous') if unchanged else ({'sources': {'core': current}} if current else None)
                extra = {kit/LOCK_FILE: lock_bytes({'sources': {'core': entry}}, previous)}
                summary = ('Core '+tag+' is already active.' if unchanged else 'Core '+(current['tag']+' -> ' if current else '')+tag+' ('+url+').')
            elif action == 'rollback':
                previous = lock.get('previous', {}).get('sources', {}).get('core')
                if not previous:
                    raise KitError('Nothing to roll back to: lock.toml has no previous configuration.')
                check_origin(previous['url'], settings)  # an origin forbidden since is not reactivated
                folder = materialize(kit, previous, settings)
                extra = {kit/LOCK_FILE: lock_bytes({'sources': {'core': previous}}, {'sources': {'core': current}} if current else None)}
                summary = 'Core '+(current['tag'] if current else '?')+' -> '+previous['tag']+' (rollback; a second rollback comes back).'
            elif current:
                check_origin(current['url'], settings)
                folder = materialize(kit, current, settings)
            with content_from(folder) if folder else contextlib.nullcontext():
                yield extra
            if summary:
                print(('[Preview] ' if dry_run else '[OK] ')+summary)
            if action in ('sync', 'rollback') and not dry_run:
                kept = read_lock(kit)
                for item in (kept.get('sources', {}).get('core'), kept.get('previous', {}).get('sources', {}).get('core')):
                    if item:
                        prune_cache(kit, item['url'], {e['tag'] for e in (kept.get('sources', {}).get('core'), kept.get('previous', {}).get('sources', {}).get('core')) if e and e['url'] == item['url']})
        finally:
            if folder:
                remove_temp(folder)


def lock_summary(kit):
    """One line for doctor: the active Core and the one rollback returns to."""
    lock = read_lock(kit)
    core = lock.get('sources', {}).get('core')
    if not core:
        return None
    previous = lock.get('previous', {}).get('sources', {}).get('core')
    return 'Core '+core['tag']+' ('+core['url']+', commit '+core['commit'][:12]+')'+(' | rollback to '+previous['tag'] if previous else '')

