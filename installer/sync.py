"""sync, team use and rollback of the Core and Team sources, and the locked content every
other command uses.

activation() is wrapped around the existing apply(): it takes the engine lock, resumes an interrupted activation, chooses
the content (the locked Core and Team, newly fetched tags, another Team, or the previous configuration), overlays the active
Team on the Core, and gives apply() the files to write in the same transaction (lock.toml, aikit.toml). Without a Core or a
Team source, the content is the package's own."""
import contextlib
from dataclasses import dataclass, field
from pathlib import Path
import shutil
from typing import Dict, Optional

from .commit import resume_pending
from .config import AIKIT_FILE, check_source, load_aikit, load_managed
from .core import ROOT, KitError, content_from, content_root, safe_id
from .resolve import agent_catalog, skill_catalog
from .sources import (verify_signature, EngineLock, SourceError, authorize, bundle_tags, cache_dir, canonical_url, check_seen, choose_tag, extract, fetch,
                      fetch_bundle, git, new_temp, prune_cache, remote_tags, remove_temp, revoked)
from .toml_files import dump_toml, read_toml, set_section_key

LOCK_FILE = 'lock.toml'
LOCK_HEADER = '# Generated by ai-kit. Do not edit: ai-kit sync, ai-kit team use and ai-kit rollback write it.\n'
TEAM_FORBIDDEN = ('commands', 'policies', 'hooks', 'runtime')
CONTENT = ('skills', 'agents', 'commands', 'context', 'templates', 'mcp', 'workflows', 'CHANGELOG.md', 'NEWS.md', AIKIT_FILE)


@dataclass
class Activation:
    writes: Dict[Path, bytes] = field(default_factory=dict)  # lock.toml and aikit.toml, in apply()'s transaction
    team: Optional[str] = None  # the team apply() uses: the active V2 Team, 'none', or None to keep the recorded one


def engine_version():
    return (ROOT/'VERSION').read_text(encoding='utf-8').strip()


def read_lock(kit):
    return read_toml(kit/LOCK_FILE, {})


def lock_bytes(current, previous):
    data = {'engine': engine_version(), **{k: v for k, v in current.items() if v}}
    if previous:
        data['previous'] = {k: v for k, v in previous.items() if v}
    return (LOCK_HEADER + dump_toml(data)).encode('utf-8')


def personal(home):
    path = home/'.ai-kit'/AIKIT_FILE
    return load_aikit(path)[0] if path.exists() else {}


def git_settings(home, managed):
    """Effective git.* keys: managed.toml wins key by key; the person may only allow prereleases when IT does not decide."""
    mine = personal(home)
    settings = {'allowed_hosts': [], 'allowed_groups': [], 'allowed_schemes': ['https', 'ssh'], 'allow_prerelease': False, 'revoked': [], 'signers': []}
    if 'allow_prerelease' in mine.get('git', {}):
        settings['allow_prerelease'] = mine['git']['allow_prerelease']
    settings.update((managed or {}).get('git', {}))
    core = (managed or {}).get('enterprise', {}).get('core') or mine.get('core', {}).get('repo')
    return settings, core, bool((managed or {}).get('enterprise', {}).get('core'))


def check_origin(url, settings):
    canonical = canonical_url(url, tuple(settings['allowed_schemes']))
    authorize(canonical, settings)
    return canonical


def check_team_allowed(url, managed):
    """managed.toml teams.allowed (URL prefixes; empty: any Team within the allowed hosts and groups)."""
    allowed = (managed or {}).get('teams', {}).get('allowed') or []
    if allowed and not any(url == a or url.startswith(a.rstrip('/')+'/') for a in allowed):
        raise SourceError('refused-origin', 'This Team is not in teams.allowed (managed.toml): '+url)


def materialize(kit, entry, settings, label):
    """The tree of a lock entry extracted into a new temporary folder, its digest checked against the lock."""
    if revoked(entry['commit'], settings):
        raise SourceError('revoked', 'The commit '+entry['commit']+' ('+label+' '+entry['tag']+') is revoked by IT (managed.toml git.revoked).')
    cache = cache_dir(kit, entry['url'])
    if not (cache/'HEAD').exists():
        raise SourceError('not-found', label+' '+entry['tag']+' is not in the local cache: run ai-kit sync (network needed).')
    folder = new_temp()
    try:
        if extract(kit, cache, entry['commit'], folder) != entry['tree_digest']:
            raise SourceError('invalid', 'The cached '+label+' '+entry['tag']+' does not match lock.toml (tree digest): run ai-kit sync.')
        if check_source(folder, engine_version()) is None:
            raise SourceError('invalid', label+' '+entry['tag']+' has no aikit.toml manifest at its root.')
        return folder
    except BaseException:
        remove_temp(folder)
        raise


def fetch_highest(kit, url, current, settings, label, bundle=None):
    """(entry, folder) for the highest eligible tag of url: ls-remote (or the tags of a bundle file, the offline origin of the
    same URL), tag-moved check, fetch of that tag only, extraction."""
    same_origin = current and current.get('url') == url
    if bundle:
        tags = bundle_tags(kit, bundle)
        tag = choose_tag(tags, current['tag'] if same_origin else None, settings['allow_prerelease'])
        cache, commit = fetch_bundle(kit, url, bundle, tag)
        announced = {'commit': commit, 'tag_object': git(['rev-parse', 'refs/tags/'+tag], kit, git_dir=cache).decode().strip()}
        check_seen(kit, url, {tag: announced})
    else:
        tags = remote_tags(url, kit, tuple(settings['allowed_schemes']))
        check_seen(kit, url, tags)
        tag = choose_tag(tags, current['tag'] if same_origin else None, settings['allow_prerelease'])
        announced = tags[tag]
    if revoked(announced['commit'], settings):
        raise SourceError('revoked', label+' '+tag+' is revoked by IT (managed.toml git.revoked); nothing was changed.')
    if not bundle:
        cache = fetch(kit, url, tag, announced['commit'], tuple(settings['allowed_schemes']))
    verify_signature(kit, cache, tag, settings.get('signers'))
    folder = new_temp()
    try:
        digest = extract(kit, cache, announced['commit'], folder)
        if check_source(folder, engine_version()) is None:
            raise SourceError('invalid', label+' '+tag+' has no aikit.toml manifest at its root; nothing was changed.')
    except BaseException:
        remove_temp(folder)
        raise
    return {'url': url, 'tag': tag, 'tag_object': announced['tag_object'], 'commit': announced['commit'], 'tree_digest': digest}, folder


def overlay(base, team_folder, name):
    """A new content tree: the Core (or the package content) with the Team on top. A Team skill or agent replaces the Core one
    of the same name unless it is protected (refused); the Team's context becomes its practice layer, its [defaults] its
    settings layer. A Team never brings commands, policies or hooks."""
    manifest = check_source(team_folder, engine_version())
    if manifest.get('kind') != 'team' or manifest.get('name') != name:
        raise SourceError('invalid', 'The Team repository must declare kind = "team" and name = "'+name+'" in its aikit.toml.')
    forbidden = [f for f in TEAM_FORBIDDEN if (team_folder/f).exists()]
    if forbidden:
        raise SourceError('invalid', 'Team '+name+' holds '+', '.join(forbidden)+', which only the Core may define; nothing was changed.')
    merged = new_temp()
    try:
        for item in CONTENT:
            source = Path(base)/item
            if source.is_dir():
                shutil.copytree(source, merged/item)
            elif source.is_file():
                shutil.copy2(source, merged/item)
        core_skills, core_agents = skill_catalog(merged), agent_catalog(merged)
        for skill, entry in skill_catalog(team_folder).items():
            if 'path' not in entry:
                continue
            if core_skills.get(skill, {}).get('protected'):
                raise SourceError('invalid', 'Team '+name+' replaces the protected Core skill '+skill+'; nothing was changed.')
            if skill in core_skills and 'path' in core_skills[skill]:
                shutil.rmtree(merged/core_skills[skill]['path'])
            shutil.copytree(team_folder/entry['path'], merged/'skills'/('team-'+name)/skill)
        for agent, entry in agent_catalog(team_folder).items():
            if core_agents.get(agent, {}).get('protected'):
                raise SourceError('invalid', 'Team '+name+' replaces the protected Core agent '+agent+'; nothing was changed.')
            if agent in core_agents:
                (merged/core_agents[agent]['path']).unlink()
            target = merged/'agents'/('team-'+name)/(agent+'.md')
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(team_folder/entry['path'], target)
        context = sorted((team_folder/'context').glob('*.md')) if (team_folder/'context').is_dir() else []
        if context:
            layers = merged/'context'
            layers.mkdir(exist_ok=True)
            (layers/('20-'+name+'.md')).write_text('\n\n'.join(p.read_text(encoding='utf-8').strip() for p in context)+'\n', encoding='utf-8')
        layer = dict(manifest.get('defaults') or {})
        servers = read_toml(team_folder/'mcp'/'servers.toml', {}).get('servers', {}) if (team_folder/'mcp'/'servers.toml').is_file() else {}
        if servers:  # the Team's own MCP servers: active for its members; a local one needs an approved identity (ADR 0022)
            layer['mcp'] = {n: {'server': {k: v for k, v in s.items() if k != 'enabled'}, 'enabled': s.get('enabled', True), 'team': True}
                            for n, s in servers.items() if isinstance(s, dict)}
        (merged/'teams').mkdir(exist_ok=True)
        (merged/'teams'/(name+'.toml')).write_text(dump_toml(layer), encoding='utf-8')
        skill_catalog(merged)  # requirements and cycles over the merged content
        return merged
    except BaseException:
        remove_temp(merged)
        raise


def aikit_text(home, updates):
    """~/.ai-kit/aikit.toml with these section keys set (targeted writes, comments kept); created when absent."""
    path = home/'.ai-kit'/AIKIT_FILE
    text = path.read_text(encoding='utf-8-sig') if path.exists() else '#:schema ./schemas/aikit.schema.json\nschema = 1\n'
    for section, key, value in updates:
        text = set_section_key(text, section, key, value, '~/.ai-kit/aikit.toml')
    return text.encode('utf-8')


@contextlib.contextmanager
def activation(home, action, dry_run=False, confirm=None, managed_file=None, guardrail_names=(), team_name=None, team_url=None, ask_url=None, bundle=None,
               shipped=False):
    """Yields an Activation for apply(), with the content root set to the active Core and Team."""
    kit = home/'.ai-kit'
    managed = load_managed(managed_file, guardrail_names)
    settings, core_url, anchored = git_settings(home, managed)
    lock = read_lock(kit)
    core_url = core_url or ((lock.get('sources') or {}).get('core') or {}).get('url')  # the Core activated first (a ZIP's)
    if bundle and shipped:
        # The Core the release ZIP ships, at the engine's own version: the package is the trust anchor (2.2).
        from .bootstrap import DEFAULT_CORE_URL
        core_url, anchored = core_url or DEFAULT_CORE_URL, True
    locker = contextlib.nullcontext() if dry_run else EngineLock(kit)
    with locker:
        if not dry_run:
            restored = resume_pending(home, kit)
            if restored:
                print('[Info] An activation was interrupted: the files of '+restored.name+' were put back before continuing.')
                lock = read_lock(kit)
        sources = lock.get('sources', {})
        core, team = sources.get('core'), sources.get('team')
        known = dict(lock.get('known_teams', {}))
        folders, result, summary = {}, Activation(), []
        new_core, new_team = core, team
        try:
            if action == 'sync':
                if not core_url and not team:
                    raise KitError('No Core source: set [core] repo = "<URL>" in ~/.ai-kit/aikit.toml, or IT sets enterprise.core in managed.toml.')
                if core_url:
                    url = check_origin(core_url, settings)
                    if not (core and core.get('url') == url) and not anchored:
                        tags = bundle_tags(kit, bundle) if bundle else remote_tags(url, kit, tuple(settings['allowed_schemes']))
                        if not bundle:
                            check_seen(kit, url, tags)
                        tag = choose_tag(tags, None, settings['allow_prerelease'])
                        # First use of an origin outside managed mode: the person confirms what will be trusted (ADR 0016).
                        question = 'First use of this Core: '+url+' at '+tag+(' from the bundle '+str(bundle) if bundle else ' (commit '+tags[tag]['commit'][:12]+')')+'. Trust it?'
                        if confirm is None or not confirm(question):
                            raise KitError('First use of '+url+' needs your confirmation in a terminal: run ai-kit sync there.')
                    new_core, folders['core'] = fetch_highest(kit, url, core, settings, 'Core', bundle)
                    summary.append('Core '+new_core['tag']+' is already active.' if new_core == core else 'Core '+(core['tag']+' -> ' if core else '')+new_core['tag']+' ('+url+').')
                if team and not bundle:  # offline: the Team stays at its locked version
                    check_origin(team['url'], settings)
                    check_team_allowed(team['url'], managed)
                    new_team, folders['team'] = fetch_highest(kit, team['url'], team, settings, 'Team '+team['name'])
                    new_team = {'name': team['name'], **new_team}
                    known[team['name']] = new_team
                    summary.append('Team '+team['name']+' '+new_team['tag']+(' is already active.' if new_team == team else ' (was '+team['tag']+').'))
            elif action == 'team-use':
                name = safe_id(team_name)
                if name == 'none':
                    new_team = None
                    result.writes[kit/AIKIT_FILE] = aikit_text(home, [('user', 'active_team', 'none')])
                    summary.append('Team '+(team['name'] if team else 'none')+' -> none (its cache is kept).')
                else:
                    url = team_url or personal(home).get('teams', {}).get(name, {}).get('repo') or known.get(name, {}).get('url')
                    if not url:
                        url = ask_url(name) if ask_url else None
                        if not url:
                            raise KitError('Unknown Team '+name+': give its repository URL, ai-kit team use '+name+' --url <URL> (or run it in a terminal).')
                        if (managed or {}).get('teams', {}).get('allow_unknown') is False:
                            raise SourceError('refused-origin', 'Adding an unknown Team is refused by IT (managed.toml teams.allow_unknown = false).')
                    url = check_origin(url, settings)
                    check_team_allowed(url, managed)
                    cached = known.get(name)
                    if cached and cached['url'] == url and (cache_dir(kit, url)/'HEAD').exists():
                        new_team = cached  # from the cache, no network; a newer version comes with sync
                    else:
                        entry, folders['team'] = fetch_highest(kit, url, None, settings, 'Team '+name)
                        new_team = {'name': name, **entry}
                    known[name] = new_team
                    result.writes[kit/AIKIT_FILE] = aikit_text(home, [('teams.'+name, 'repo', url), ('user', 'active_team', name)])
                    summary.append('Team '+(team['name'] if team else 'none')+' -> '+name+' '+new_team['tag']+'.')
            elif action == 'rollback':
                previous = lock.get('previous', {})
                if not previous.get('sources'):
                    raise KitError('Nothing to roll back to: lock.toml has no previous configuration.')
                new_core, new_team = previous['sources'].get('core'), previous['sources'].get('team')
                for entry in (new_core, new_team):
                    if entry:
                        check_origin(entry['url'], settings)  # an origin forbidden since is not reactivated
                result.writes[kit/AIKIT_FILE] = aikit_text(home, [('user', 'active_team', new_team['name'] if new_team else 'none')])
                summary.append('Rollback: Core '+(new_core['tag'] if new_core else 'package')+', Team '+(new_team['name']+' '+new_team['tag'] if new_team else 'none')+' (a second rollback comes back).')
            # Content: Core extracted at its commit (or the package's), then the Team on top.
            if new_core and 'core' not in folders:
                check_origin(new_core['url'], settings)
                folders['core'] = materialize(kit, new_core, settings, 'Core')
            if new_team and 'team' not in folders:
                check_origin(new_team['url'], settings)
                folders['team'] = materialize(kit, new_team, settings, 'Team '+new_team['name'])
            content = folders.get('core')
            if new_team:
                folders['merged'] = overlay(folders.get('core') or content_root(), folders['team'], new_team['name'])
                content = folders['merged']
                result.team = new_team['name']
            elif action in ('team-use', 'rollback') and team:
                result.team = 'none'
            if action in ('sync', 'team-use', 'rollback'):
                current = {'sources': {k: v for k, v in (('core', new_core), ('team', new_team)) if v}, 'known_teams': known}
                old = {'sources': {k: v for k, v in (('core', core), ('team', team)) if v}}
                unchanged = current['sources'] == old['sources']
                previous = lock.get('previous') if unchanged else old
                result.writes[kit/LOCK_FILE] = lock_bytes(current, previous if previous and previous.get('sources') else None)
            with content_from(content) if content else contextlib.nullcontext():
                yield result
            for line in summary:
                print(('[Preview] ' if dry_run else '[OK] ')+line)
            if action in ('sync', 'team-use', 'rollback') and not dry_run:
                prune_all(kit)
        finally:
            for folder in folders.values():
                remove_temp(folder)


@contextlib.contextmanager
def shipped_core(home, bundle):
    """The highest tag of the shipped bundle, extracted into a temporary folder for this run (menus, checks); nothing is
    recorded: the installation that follows activates it and writes lock.toml (activation with shipped=True)."""
    kit = home/'.ai-kit'
    kit.mkdir(parents=True, exist_ok=True)
    from .bootstrap import DEFAULT_CORE_URL
    settings, core_url, _ = git_settings(home, load_managed(None))  # IT's enterprise.core wins
    url = check_origin(core_url or DEFAULT_CORE_URL, settings)
    tag = choose_tag(bundle_tags(kit, bundle), None, settings['allow_prerelease'])
    cache, commit = fetch_bundle(kit, url, bundle, tag)
    folder = new_temp()
    try:
        extract(kit, cache, commit, folder)
        if check_source(folder, engine_version()) is None:
            raise SourceError('invalid', 'The shipped Core '+tag+' has no aikit.toml manifest.')
        yield folder
    finally:
        remove_temp(folder)


def prune_all(kit):
    """The caches keep the tags lock.toml cites: active, previous, and the cached version of each known Team."""
    lock = read_lock(kit)
    entries = list(lock.get('sources', {}).values()) + list(lock.get('previous', {}).get('sources', {}).values()) + list(lock.get('known_teams', {}).values())
    for url in {e['url'] for e in entries}:
        prune_cache(kit, url, {e['tag'] for e in entries if e['url'] == url})


def lock_summary(kit):
    """One line for doctor and status: the active Core and Team, and what rollback returns to."""
    lock = read_lock(kit)
    sources = lock.get('sources', {})
    if not sources:
        return None
    core, team = sources.get('core'), sources.get('team')
    previous = lock.get('previous', {}).get('sources', {})
    parts = ['Core '+core['tag']+' ('+core['url']+', commit '+core['commit'][:12]+')' if core else 'Core: the package content']
    parts.append('Team '+team['name']+' '+team['tag'] if team else 'Team: none')
    if previous:
        parts.append('rollback to '+', '.join(k+' '+v['tag'] for k, v in previous.items()))
    return ' | '.join(parts)


def newer_available(kit):
    """['Core v1.2.0', 'Team data v2.0.0'] when the tags seen by the last ls-remote (sync, team use) are above the locked ones; no
    network here (status, doctor)."""
    import json
    from .sources import STABLE_TAG, engine_dir, source_id, tag_key
    found = []
    for label, entry in sorted(read_lock(kit).get('sources', {}).items()):
        path = engine_dir(kit)/(source_id(entry['url'])+'.seen.json')
        try:
            seen = json.loads(path.read_text(encoding='utf-8'))
        except (OSError, ValueError):
            continue
        stable = [t for t in seen if STABLE_TAG.match(t)]
        if stable and STABLE_TAG.match(entry['tag']) and tag_key(max(stable, key=tag_key)) > tag_key(entry['tag']):
            found.append(('Core' if label == 'core' else 'Team '+entry.get('name', ''))+' '+max(stable, key=tag_key))
    return found


def team_list(home):
    """Known Teams (aikit.toml and lock.toml), the active one, the cached version: no network."""
    kit = home/'.ai-kit'
    lock = read_lock(kit)
    active = lock.get('sources', {}).get('team', {}).get('name')
    names = sorted(set(personal(home).get('teams', {})) | set(lock.get('known_teams', {})))
    if not names:
        print('No Team known. Add one: ai-kit team use <name> --url <URL>.')
        return 0
    for name in names:
        cached = lock.get('known_teams', {}).get(name)
        url = personal(home).get('teams', {}).get(name, {}).get('repo') or (cached or {}).get('url', '?')
        print(('* ' if name == active else '  ')+name+'  '+(cached['tag'] if cached else 'not downloaded')+'  '+url)
    return 0
