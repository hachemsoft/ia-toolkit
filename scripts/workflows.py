"""The workflow indexes of the Core (ADR 0026, docs/v2/resources.md): workflows/sdlc.md is generated from the commands (step,
command, skills, artifact), never a second source of prompts; analysis.md and research.md point to their entry command and
skill. A test checks they are current.

Usage: python3 scripts/workflows.py           prints what differs
       python3 scripts/workflows.py --write   rewrites workflows/
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from installer.core import load_commands  # noqa: E402

STAGES = ('Plan', 'Design', 'Build', 'Test', 'Deploy', 'Maintain')


def sdlc():
    rows = ['# SDLC workflow', '', 'Generated by scripts/workflows.py from commands/: an index, never a prompt. The levels quick, standard and full',
            'are defined once, in the kit context. A small question gets a direct answer, without this workflow.', '',
            '| Step | Command | Skills | Artifact | Installed |', '| --- | --- | --- | --- | --- |']
    commands = [c for c in load_commands() if c.get('stage')]
    for stage in STAGES:
        for c in (c for c in commands if c['stage'] == stage):
            rows.append('| '+stage+' | `/'+c['name']+'` | '+', '.join(c['skills'])+' | '+c.get('artifact', '')+' | '
                        + ('default' if c.get('default', True) else 'optional')+' |')
    return '\n'.join(rows)+'\n'


ANALYSIS = """# Analysis workflow

An index, never a prompt (ADR 0026). Entry: `/explain` with a question about the project; skill `analysis`; agents
repo-investigator and verifier when installed.

1. Frame the question in one line.
2. Explore the project's own sources.
3. Verify each claim: observed (file, line, read-only command) or assumed.
4. Report: verdict, evidence, unknowns.

A Team extends it through the "In the kit commands" section of its skills (`### /explain`).
"""

RESEARCH = """# Research workflow

An index, never a prompt (ADR 0026). Entry: `/research`; skill `investigation`; agent doubter for the challenge step when
installed.

1. Frame the question and the criteria.
2. Search primary sources; compare the options.
3. Challenge: counter-examples, assumptions that change the result.
4. Recommend one option and one ruled-out alternative; record it in the repo.

A Team extends it through the "In the kit commands" section of its skills (`### /research`).
"""


def files():
    return {'sdlc.md': sdlc(), 'analysis.md': ANALYSIS, 'research.md': RESEARCH}


if __name__ == '__main__':
    folder = ROOT/'workflows'
    if '--write' in sys.argv:
        folder.mkdir(exist_ok=True)
        for name, text in files().items():
            (folder/name).write_text(text, encoding='utf-8')
        print('workflows/ written.')
    else:
        stale = [n for n, text in files().items() if not (folder/n).is_file() or (folder/n).read_text(encoding='utf-8') != text]
        print('workflows/: '+(', '.join(stale)+' to rewrite (--write)' if stale else 'current.'))
        sys.exit(1 if stale else 0)
